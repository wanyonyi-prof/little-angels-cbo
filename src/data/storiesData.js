// Get a single story by slug
export const getStoryBySlug = (slug) => {
  return storiesData.find(story => story.slug === slug);
};

// Get related stories (excluding current one)
export const getRelatedStories = (currentSlug, limit = 2) => {
  return storiesData
    .filter(story => story.slug !== currentSlug)
    .slice(0, limit);
};

// Get featured story
export const getFeaturedStory = () => {
  return storiesData.find(story => story.featured) || storiesData[0];
};